// Export writes c as Terraform with the native azurerm_* resources, in a
// single main.tf that Load reads back. What the provider cannot say is
// left as comments: Geo-Replication, the message-size metadata and the
// keys of access policies, which Terraform computes.
func Export(c *config.Config) string {
	e := &exporter{labels: map[string]bool{}}
	e.line("# Generated by open-service-bus.")
	e.line("")
	namespaces := []*config.Config{c}
	if len(c.Namespaces) > 0 {
		namespaces = c.Namespaces
	}
	byName := map[string]string{}
	for i, ns := range namespaces {
		name := ns.Name
		if name == "" {
			name = "emulator"
		}
		byName[strings.ToLower(name)] = e.namespace(i, name, ns)
	}
	for _, g := range c.GeoDR {
		p, ok1 := byName[strings.ToLower(g.Primary)]
		s, ok2 := byName[strings.ToLower(g.Secondary)]
		if !ok1 || !ok2 {
			continue
		}
		e.line("resource \"azurerm_servicebus_namespace_disaster_recovery_config\" %s {", e.label("geodr", g.Alias))
		e.line("  name                 = %s", quote(g.Alias))
		e.line("  primary_namespace_id = azurerm_servicebus_namespace.%s.id", p)
		e.line("  partner_namespace_id = azurerm_servicebus_namespace.%s.id", s)
		e.line("}")
		e.line("")
	}
	return string(hclwrite.Format([]byte(e.b.String())))
}

type exporter struct {
	b      strings.Builder
	labels map[string]bool
}

func (e *exporter) line(format string, args ...any) {
	fmt.Fprintf(&e.b, format+"\n", args...)
}

var unsafeLabel = regexp.MustCompile(`[^A-Za-z0-9_]+`)

// label returns a unique resource label, as a quoted HCL string.
func (e *exporter) label(prefix string, parts ...string) string {
	base := prefix + "_" + unsafeLabel.ReplaceAllString(strings.Join(parts, "_"), "_")
	l := base
	for i := 2; e.labels[l]; i++ {
		l = base + "_" + strconv.Itoa(i)
	}
	e.labels[l] = true
	return quote(l)
}

// ref is the unquoted form of a label made by label.
func ref(label string) string { return strings.Trim(label, `"`) }

func quote(s string) string {
	q := strconv.Quote(s)
	q = strings.ReplaceAll(q, "${", "$${")
	return strings.ReplaceAll(q, "%{", "%%{")
}

func (e *exporter) namespace(i int, name string, c *config.Config) string {
	rg := e.label("rg", name)
	nsLabel := e.label("ns", name)
	e.line("resource \"azurerm_resource_group\" %s {", rg)
	e.line("  name     = %s", quote(name))
	e.line("  location = \"westeurope\"")
	e.line("}")
	e.line("")
	e.line("resource \"azurerm_servicebus_namespace\" %s {", nsLabel)
	e.line("  name                = %s", quote(name))
	e.line("  resource_group_name = azurerm_resource_group.%s.name", ref(rg))
	e.line("  location            = azurerm_resource_group.%s.location", ref(rg))
	e.line("  sku                 = \"Premium\"")
	e.line("  capacity            = 1")
	if c.Partitions > 0 {
		e.line("  premium_messaging_partitions = %d", c.Partitions)
	}
	if c.LocalAuthDisabled {
		e.line("  local_auth_enabled  = false")
	}
	if len(c.Tags) > 0 {
		e.line("  tags = {")
		for _, k := range sortedKeys(c.Tags) {
			e.line("    %s = %s", quote(k), quote(c.Tags[k]))
		}
		e.line("  }")
	}
	if enc := c.Encryption; enc != nil {
		if enc.Identity != "" {
			e.line("  identity {")
			e.line("    type         = \"UserAssigned\"")
			e.line("    identity_ids = [%s]", quote(enc.Identity))
			e.line("  }")
		}
		key := ""
		if len(enc.KeyVaultKeyIDs) > 0 {
			key = enc.KeyVaultKeyIDs[0]
		}
		e.line("  customer_managed_key {")
		e.line("    key_vault_key_id                  = %s", quote(key))
		if enc.Identity != "" {
			e.line("    identity_id                       = %s", quote(enc.Identity))
		}
		e.line("    infrastructure_encryption_enabled = %t", enc.InfrastructureEncryption)
		e.line("  }")
	}
	e.line("}")
	e.line("")
	if g := c.GeoReplication; g != nil {
		mode := "asynchronous"
		if g.Synchronous {
			mode = "synchronous"
		}
		e.line("# Geo-Replication (%s, %s -> %s) has no Terraform resource; configure it in", mode, g.PrimaryRegion, g.SecondaryRegion)
		e.line("# the emulator's Config.json or portal.")
		e.line("")
	}

	ns := ref(nsLabel)
	nsID := "azurerm_servicebus_namespace." + ns + ".id"
	ids := map[string]string{"": nsID} // lock scope -> reference to its id
	for _, q := range c.Queues {
		l := e.label("queue", name, q.Name)
		ids[broker.NormalizePath(q.Name)] = "azurerm_servicebus_queue." + ref(l) + ".id"
		e.line("resource \"azurerm_servicebus_queue\" %s {", l)
		e.line("  name         = %s", quote(q.Name))
		e.line("  namespace_id = %s", nsID)
		e.properties(broker.KindQueue, q.Properties)
		e.line("}")
		e.line("")
	}
	for _, t := range c.Topics {
		tl := e.label("topic", name, t.Name)
		tID := "azurerm_servicebus_topic." + ref(tl) + ".id"
		ids[broker.NormalizePath(t.Name)] = tID
		e.line("resource \"azurerm_servicebus_topic\" %s {", tl)
		e.line("  name         = %s", quote(t.Name))
		e.line("  namespace_id = %s", nsID)
		e.properties(broker.KindTopic, t.Properties)
		e.line("}")
		e.line("")
		for _, s := range t.Subscriptions {
			sl := e.label("sub", name, t.Name, s.Name)
			sID := "azurerm_servicebus_subscription." + ref(sl) + ".id"
			ids[broker.SubscriptionPath(t.Name, s.Name)] = sID
			e.line("resource \"azurerm_servicebus_subscription\" %s {", sl)
			e.line("  name     = %s", quote(s.Name))
			e.line("  topic_id = %s", tID)
			e.properties(broker.KindSubscription, s.Properties)
			e.line("}")
			e.line("")
			e.rules(name, t.Name, s, sID)
		}
	}
	for _, p := range c.Policies {
		typ, arg, id := "azurerm_servicebus_namespace_authorization_rule", "namespace_id", nsID
		if p.Scope != "" {
			target, ok := ids[p.Scope]
			if !ok {
				continue
			}
			arg, id = "queue_id", target
			typ = "azurerm_servicebus_queue_authorization_rule"
			if strings.HasPrefix(target, "azurerm_servicebus_topic.") {
				typ, arg = "azurerm_servicebus_topic_authorization_rule", "topic_id"
			}
		}
		e.line("resource %q %s {", typ, e.label("rule", name, p.Scope, p.Name))
		e.line("  name = %s", quote(p.Name))
		e.line("  %s = %s", arg, id)
		e.line("  listen = %t", p.Rights.Has(1))
		e.line("  send   = %t", p.Rights.Has(2))
		e.line("  manage = %t", p.Rights.Has(4))
		e.line("}")
		e.line("")
	}
	for _, a := range c.Assignments {
		target, ok := ids[a.Scope]
		if !ok {
			continue
		}
		e.line("resource \"azurerm_role_assignment\" %s {", e.label("role", name, a.Scope, a.Principal))
		e.line("  scope                = %s", target)
		e.line("  role_definition_name = %s", quote(string(a.Role)))
		e.line("  principal_id         = %s", quote(a.Principal))
		e.line("}")
		e.line("")
	}
	for _, l := range c.Locks {
		target, ok := ids[l.Scope]
		if !ok {
			continue
		}
		e.line("resource \"azurerm_management_lock\" %s {", e.label("lock", name, l.Name))
		e.line("  name       = %s", quote(l.Name))
		e.line("  scope      = %s", target)
		e.line("  lock_level = %s", quote(string(l.Level)))
		if l.Notes != "" {
			e.line("  notes      = %s", quote(l.Notes))
		}
		e.line("}")
		e.line("")
	}
	return ns
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// properties writes the arguments that differ from the defaults of kind,
// under the names the provider has for kind.
func (e *exporter) properties(kind broker.EntityKind, p broker.Properties) {
	if p == (broker.Properties{}) {
		return
	}
	d := broker.DefaultProperties(kind)
	dur := func(name string, v, def time.Duration) {
		if v != def {
			e.line("  %s = %s", name, quote(duration.Format(v)))
		}
	}
	flag := func(name string, v, def bool) {
		if v != def {
			e.line("  %s = %t", name, v)
		}
	}
	str := func(name, v, def string) {
		if v != def {
			e.line("  %s = %s", name, quote(v))
		}
	}
	num := func(name string, v, def int64) {
		if v != def {
			e.line("  %s = %d", name, v)
		}
	}
	isTopic, isSub := kind == broker.KindTopic, kind == broker.KindSubscription
	if !isTopic {
		dur("lock_duration", p.LockDuration, d.LockDuration)
		num("max_delivery_count", int64(p.MaxDeliveryCount), int64(d.MaxDeliveryCount))
		flag("dead_lettering_on_message_expiration", p.DeadLetteringOnMessageExpiration, d.DeadLetteringOnMessageExpiration)
		str("forward_to", p.ForwardTo, "")
		str("forward_dead_lettered_messages_to", p.ForwardDeadLetteredMessagesTo, "")
		flag("requires_session", p.RequiresSession, d.RequiresSession)
	}
	if isSub {
		flag("dead_lettering_on_filter_evaluation_error", p.DeadLetteringOnFilterEvaluationExceptions, d.DeadLetteringOnFilterEvaluationExceptions)
	} else {
		num("max_size_in_megabytes", p.MaxSizeInMegabytes, d.MaxSizeInMegabytes)
		num("max_message_size_in_kilobytes", p.MaxMessageSizeInKilobytes, d.MaxMessageSizeInKilobytes)
		flag("requires_duplicate_detection", p.RequiresDuplicateDetection, d.RequiresDuplicateDetection)
		dur("duplicate_detection_history_time_window", p.DuplicateDetectionHistoryTimeWindow, d.DuplicateDetectionHistoryTimeWindow)
		flag("partitioning_enabled", p.EnablePartitioning, d.EnablePartitioning)
		flag("express_enabled", p.EnableExpress, d.EnableExpress)
	}
	if isTopic {
		flag("support_ordering", p.SupportOrdering, d.SupportOrdering)
	}
	dur("default_message_ttl", p.DefaultMessageTimeToLive, d.DefaultMessageTimeToLive)
	dur("auto_delete_on_idle", p.AutoDeleteOnIdle, d.AutoDeleteOnIdle)
	flag("batched_operations_enabled", p.EnableBatchedOperations, d.EnableBatchedOperations)
	str("status", string(p.Status), string(d.Status))
	if p.UserMetadata != "" {
		e.line("  # user_metadata = %s (no Terraform argument)", quote(p.UserMetadata))
	}
}

// rules writes the rules of a subscription. A subscription that keeps only
// $Default has none to write.
func (e *exporter) rules(ns, topic string, s server.Subscription, subID string) {
	if s.Rules == nil {
		return
	}
	hasDefault := false
	for _, r := range s.Rules {
		hasDefault = hasDefault || (r.Name == broker.DefaultRuleName && r.Filter.Kind == broker.FilterTrue && r.Action == "")
	}
	if !hasDefault {
		e.line("# %s/%s has no $Default rule. Azure creates it with every subscription:", topic, s.Name)
		e.line("# delete it there, or read this with -tf-drop-default-rule.")
		e.line("")
	}
	for _, r := range s.Rules {
		if r.Name == broker.DefaultRuleName && r.Filter.Kind == broker.FilterTrue && r.Action == "" {
			continue
		}
		e.line("resource \"azurerm_servicebus_subscription_rule\" %s {", e.label("rule", ns, topic, s.Name, r.Name))
		e.line("  name            = %s", quote(r.Name))
		e.line("  subscription_id = %s", subID)
		switch r.Filter.Kind {
		case broker.FilterCorrelation:
			e.line("  filter_type     = \"CorrelationFilter\"")
			f := r.Filter.Correlation
			e.line("  correlation_filter {")
			for _, kv := range [][2]string{
				{"content_type", f.ContentType}, {"correlation_id", f.CorrelationID}, {"label", f.Subject},
				{"message_id", f.MessageID}, {"reply_to", f.ReplyTo}, {"reply_to_session_id", f.ReplyToSessionID},
				{"session_id", f.SessionID}, {"to", f.To},
			} {
				if kv[1] != "" {
					e.line("    %s = %s", kv[0], quote(kv[1]))
				}
			}
			if len(f.Properties) > 0 {
				keys := make([]string, 0, len(f.Properties))
				for k := range f.Properties {
					keys = append(keys, k)
				}
				sort.Strings(keys)
				e.line("    properties = {")
				for _, k := range keys {
					switch v := f.Properties[k].(type) {
					case string:
						e.line("      %s = %s", quote(k), quote(v))
					case bool, int, int8, int16, int32, int64, uint, uint8, uint16, uint32, uint64, float32, float64:
						e.line("      %s = %v", quote(k), v)
					default:
						e.line("      %s = %s", quote(k), quote(fmt.Sprint(v)))
					}
				}
				e.line("    }")
			}
			e.line("  }")
		default:
			expr := r.Filter.SQL
			switch r.Filter.Kind {
			case broker.FilterTrue:
				expr = "1=1"
			case broker.FilterFalse:
				expr = "1=0"
			}
			e.line("  filter_type     = \"SqlFilter\"")
			e.line("  sql_filter      = %s", quote(expr))
		}
		if r.Action != "" {
			e.line("  action          = %s", quote(r.Action))
		}
		e.line("}")
		e.line("")
	}
}
